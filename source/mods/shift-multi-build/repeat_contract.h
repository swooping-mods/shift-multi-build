static inline int moon_repeat_contract_matches(const unsigned char *image) {
    if (!image)
        return 0;
    for (unsigned i = 0; i < sizeof(moon_repeat_code_guards)/sizeof(*moon_repeat_code_guards); i++) {
        const MoonRepeatCodeGuard *guard = moon_repeat_code_guards + i;
        for (unsigned j = 0; j < guard->size; j++)
            if (image[guard->rva + j] != guard->bytes[j])
                return 0;
    }
    return 1;
}
